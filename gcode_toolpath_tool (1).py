"""
G-Code Toolpath Generator & Analyzer
--------------------------------------
A small CNC utility with two functions:

1. GENERATE  - Creates G-code for a rectangular pocket milling operation
               (a very common CNC machining task) given basic parameters:
               pocket width/height, depth, tool diameter, stepover, and
               feed rates. Uses a simple zig-zag (raster) toolpath and
               multiple depth passes.

2. ANALYZE   - Reads any G-code file and reports useful statistics:
               total rapid (G0) travel distance, total feed (G1/G2/G3)
               travel distance, number of tool changes, and an estimated
               machining time based on the feed rates used in the file.

Why this exists: G-code files are just text instructions, so they can be
parsed and generated with plain Python + regular string handling - no
special libraries needed. This script is meant as a learning project to
understand CNC toolpaths programmatically rather than only through CAM
software.

Usage:
    python gcode_toolpath_tool.py generate --width 40 --height 20 --depth 6 \
        --tool-diameter 6 --stepover 0.5 --feed 300 --plunge-rate 100 \
        --output pocket.nc

    python gcode_toolpath_tool.py analyze pocket.nc
"""

import argparse
import math
import re
import sys


# ---------------------------------------------------------------------
# 1. GENERATOR: rectangular pocket, raster (zig-zag) toolpath
# ---------------------------------------------------------------------

def generate_pocket_gcode(width, height, depth, tool_diameter,
                           stepover=0.5, feedrate=300, plunge_rate=100,
                           safe_z=5.0, depth_per_pass=2.0):
    """
    Build G-code for milling a rectangular pocket using a raster
    (back-and-forth) toolpath, cut in multiple depth passes.

    stepover is given as a fraction of the tool diameter (0.5 = 50%
    overlap between passes, a common conservative default).
    """
    step = tool_diameter * stepover
    if step <= 0:
        raise ValueError("stepover must be > 0")

    # Keep the tool centerline inside the pocket by half the tool radius
    radius = tool_diameter / 2
    x_min, x_max = radius, width - radius
    y_min, y_max = radius, height - radius

    if x_max <= x_min or y_max <= y_min:
        raise ValueError("Tool diameter is too large for this pocket size")

    n_depth_passes = max(1, math.ceil(depth / depth_per_pass))
    n_y_lines = max(1, math.ceil((y_max - y_min) / step) + 1)

    lines = []
    lines.append("; Rectangular pocket - generated by gcode_toolpath_tool.py")
    lines.append(f"; width={width}mm height={height}mm depth={depth}mm "
                  f"tool_dia={tool_diameter}mm stepover={stepover}")
    lines.append("G21 ; units = mm")
    lines.append("G90 ; absolute positioning")
    lines.append(f"G0 Z{safe_z:.3f}")
    lines.append(f"G0 X{x_min:.3f} Y{y_min:.3f}")

    current_z = 0.0
    for pass_num in range(1, n_depth_passes + 1):
        current_z = -min(depth, depth_per_pass * pass_num)
        lines.append(f"; --- depth pass {pass_num}/{n_depth_passes}, "
                      f"Z={current_z:.3f} ---")
        lines.append(f"G1 Z{current_z:.3f} F{plunge_rate}")

        going_right = True
        for i in range(n_y_lines):
            y = min(y_min + i * step, y_max)
            x_target = x_max if going_right else x_min
            lines.append(f"G1 X{x_target:.3f} Y{y:.3f} F{feedrate}")
            if i < n_y_lines - 1:
                # step over to the next line
                next_y = min(y_min + (i + 1) * step, y_max)
                lines.append(f"G1 Y{next_y:.3f} F{feedrate}")
            going_right = not going_right

        lines.append(f"G0 Z{safe_z:.3f}")
        lines.append(f"G0 X{x_min:.3f} Y{y_min:.3f}")

    lines.append("M5 ; spindle off")
    lines.append("M2 ; program end")
    return lines


# ---------------------------------------------------------------------
# 2. ANALYZER: parse an existing G-code file and report stats
# ---------------------------------------------------------------------

_COORD_RE = re.compile(r'([XYZ])(-?\d+\.?\d*)')
_FEED_RE = re.compile(r'F(\d+\.?\d*)')


def analyze_gcode(filepath):
    rapid_distance = 0.0
    feed_distance = 0.0
    tool_changes = 0
    time_seconds = 0.0
    current = {"X": 0.0, "Y": 0.0, "Z": 0.0}
    current_feed = None  # mm/min
    line_count = 0

    with open(filepath, "r") as f:
        for raw_line in f:
            line = raw_line.split(";")[0].strip()  # strip comments
            if not line:
                continue
            line_count += 1

            if line.upper().startswith("T"):
                tool_changes += 1

            feed_match = _FEED_RE.search(line)
            if feed_match:
                current_feed = float(feed_match.group(1))

            is_rapid = line.upper().startswith("G0") or " G0" in line.upper()
            is_feed_move = line.upper().startswith(("G1", "G2", "G3"))

            if is_rapid or is_feed_move:
                target = dict(current)
                for axis, value in _COORD_RE.findall(line):
                    target[axis] = float(value)

                dist = math.sqrt(
                    (target["X"] - current["X"]) ** 2 +
                    (target["Y"] - current["Y"]) ** 2 +
                    (target["Z"] - current["Z"]) ** 2
                )

                if is_rapid:
                    rapid_distance += dist
                    # assume a typical rapid traverse rate for time estimate
                    time_seconds += dist / (5000 / 60)  # 5000 mm/min rapids
                else:
                    feed_distance += dist
                    if current_feed:
                        time_seconds += dist / (current_feed / 60)

                current = target

    return {
        "lines_parsed": line_count,
        "rapid_distance_mm": round(rapid_distance, 2),
        "feed_distance_mm": round(feed_distance, 2),
        "tool_changes": tool_changes,
        "estimated_time_min": round(time_seconds / 60, 2),
    }


def print_report(stats, filepath):
    print(f"\nG-code analysis: {filepath}")
    print("-" * 40)
    print(f"Lines parsed:            {stats['lines_parsed']}")
    print(f"Rapid (G0) travel:       {stats['rapid_distance_mm']} mm")
    print(f"Feed (G1/2/3) travel:    {stats['feed_distance_mm']} mm")
    print(f"Tool changes:            {stats['tool_changes']}")
    print(f"Estimated machine time:  {stats['estimated_time_min']} min")
    print("-" * 40)


# ---------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------

def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                      formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)

    gen = sub.add_parser("generate", help="Generate G-code for a rectangular pocket")
    gen.add_argument("--width", type=float, required=True, help="Pocket width (mm)")
    gen.add_argument("--height", type=float, required=True, help="Pocket height (mm)")
    gen.add_argument("--depth", type=float, required=True, help="Pocket depth (mm)")
    gen.add_argument("--tool-diameter", type=float, required=True, help="Tool diameter (mm)")
    gen.add_argument("--stepover", type=float, default=0.5, help="Stepover as fraction of tool diameter (default 0.5)")
    gen.add_argument("--feed", type=float, default=300, help="Cutting feed rate mm/min (default 300)")
    gen.add_argument("--plunge-rate", type=float, default=100, help="Plunge feed rate mm/min (default 100)")
    gen.add_argument("--depth-per-pass", type=float, default=2.0, help="Depth per pass mm (default 2.0)")
    gen.add_argument("--output", default="pocket.nc", help="Output filename (default pocket.nc)")

    ana = sub.add_parser("analyze", help="Analyze an existing G-code file")
    ana.add_argument("filepath", help="Path to .nc / .gcode file")

    args = parser.parse_args()

    if args.command == "generate":
        lines = generate_pocket_gcode(
            width=args.width, height=args.height, depth=args.depth,
            tool_diameter=args.tool_diameter, stepover=args.stepover,
            feedrate=args.feed, plunge_rate=args.plunge_rate,
            depth_per_pass=args.depth_per_pass,
        )
        with open(args.output, "w") as f:
            f.write("\n".join(lines) + "\n")
        print(f"Wrote {len(lines)} lines of G-code to {args.output}")

    elif args.command == "analyze":
        stats = analyze_gcode(args.filepath)
        print_report(stats, args.filepath)


if __name__ == "__main__":
    main()
